SELECT
    CASE_ID,
    WORKFLOW_STAGE,
    POSTGUARD_STATUS,
    AWKEY
FROM CASHAPP.CASES
WHERE CASE_ID = '<case_id>';


SELECT
    CASE_ID,
    CHECK_SEQUENCE,
    CHECK_NAME,
    PASSED,
    REASON_CODE,
    DETAIL,
    CHECK_DATA,
    RUN_AT
FROM CASHAPP.CASE_POSTGUARD_CHECKS
WHERE CASE_ID = '<case_id>'
ORDER BY RUN_AT DESC, CHECK_SEQUENCE;



SELECT
    EVENT_TYPE,
    EVENT_MESSAGE,
    EVENT_DATA,
    OCCURRED_AT
FROM CASHAPP.CASE_EVENTS
WHERE CASE_ID = '<case_id>'
  AND EVENT_TYPE IN ('POSTGUARD_PASS', 'POSTGUARD_FAIL')
ORDER BY OCCURRED_AT DESC;



SELECT
    C.CASE_ID,
    C.POSTGUARD_STATUS,
    C.WORKFLOW_STAGE,
    C.AWKEY,
    COUNT(P.CHECK_ID) AS CHECKS_WRITTEN,
    SUM(IFF(P.PASSED, 1, 0)) AS CHECKS_PASSED,
    SUM(IFF(NOT P.PASSED, 1, 0)) AS CHECKS_FAILED
FROM CASHAPP.CASES C
LEFT JOIN CASHAPP.CASE_POSTGUARD_CHECKS P
    ON P.CASE_ID = C.CASE_ID
WHERE C.CASE_ID = '<case_id>'
GROUP BY
    C.CASE_ID,
    C.POSTGUARD_STATUS,
    C.WORKFLOW_STAGE,
    C.AWKEY;


SELECT
    QUERY_ID,
    QUERY_TEXT,
    EXECUTION_STATUS,
    ERROR_CODE,
    ERROR_MESSAGE,
    START_TIME,
    END_TIME
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY())
WHERE QUERY_TEXT ILIKE '%RUN_POSTGUARD%'
ORDER BY START_TIME DESC
LIMIT 20;



